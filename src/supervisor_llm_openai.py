"""Thin wrapper over the OpenAI Chat Completions API, shaped to satisfy the
same interface supervisor_llm.OllamaClient does -- `.chat(messages,
tools=None)` returning an object with `.message.content` (str) and
`.message.tool_calls` (a list of objects with `.function.name`/
`.function.arguments`) -- so supervisor_session_pid.Session and
supervisor_session_lqg.LQGSession work against this client completely
unmodified. Structured the same way supervisor_llm_anthropic.AnthropicClient
is (see that module's docstring for the general shape of the problem); this
one differs where OpenAI's own API genuinely differs, verified against the
current openai-python SDK source and API docs as of this writing (2026-09),
not assumed safe by analogy to the Anthropic client:

- **Chat Completions, not the Responses API.** OpenAI's docs now call
  Responses primary, but Chat Completions is documented as supported
  indefinitely and is structurally the closer match to every other client
  in this file (Ollama, Anthropic) -- a flat messages list with role-tagged
  entries, not Responses' separate call_id-addressed input/output items.
  Deliberate choice, not an oversight -- see docs/aituner_plan.md.
- **No tool-schema translation needed.** The `{"type": "function",
  "function": {"name", "description", "parameters"}}` shape already used
  throughout supervisor_tools_*.py (built for Ollama) *is* the Chat
  Completions tools= shape -- OpenAI's is the schema Ollama's own
  tool-calling convention followed in the first place. Tools are passed
  straight through in `.chat()`; there is no `_to_openai_tools` here, unlike
  the Anthropic client's `_to_anthropic_tools`.
- **`role: "system"` is a normal message, not a separate top-level
  parameter** (unlike Anthropic's `system=`) -- confirmed against the SDK's
  own `chat_completion_system_message_param.py`, still present. So
  `_translate_messages` here returns one flat messages list, no
  `(system_text, messages)` tuple.
- **No same-turn tool-result batching required.** Anthropic requires every
  tool_result for one assistant turn to land in a single following `user`
  message; Chat Completions has no such rule -- each tool result is its own
  independent `{"role": "tool", "tool_call_id": ..., "content": ...}`
  message, appended one after another. Confirmed against
  `chat_completion_tool_message_param.py`.
- **`function.arguments` comes back as a JSON *string*, not a dict**
  (confirmed against `chat_completion_message_function_tool_call.py`'s own
  field docstring: "as generated by the model in JSON format") -- the
  opposite of Anthropic's `tool_use.input`, which is already a dict. This
  client `json.loads()`s it once, at receipt, before handing Session the
  Ollama-shaped `.tool_calls` surface Session expects a dict from.
- **`max_completion_tokens`, not `max_tokens`.** The latter is documented
  as deprecated on the Chat Completions endpoint and incompatible with
  reasoning-tier models -- confirmed against `completion_create_params.py`.
- **The id-collision risk this project already hit once (see
  docs/memos/2026-09-07/2026-09-07-supervisor-robustness-memo.md section 3)
  applies here too, for the same reason** -- it's Session's own
  name-keyed `{"role": "tool", "tool_name": ...}` result dicts that create
  the risk, not anything Anthropic-specific, and Chat Completions is
  id-based (`tool_calls[].id` / `tool_call_id`) the same way Anthropic's
  Messages API is. Ported the identical fix: a per-name FIFO queue of ids,
  not a single last-id-per-name dict.

Model default: gpt-5.6-luna (cheapest current tier per OpenAI's own pricing
docs, mirroring the Haiku-is-default choice in supervisor_llm_anthropic.py --
gpt-5.6-sol/gpt-6-astra deliberately not offered as defaults for the same
"most expensive tier, no reason to default to it" reasoning as Opus there).
"""

from __future__ import annotations

from collections import defaultdict
import json

import openai

DEFAULT_MODEL = "gpt-5.6-luna"
DEFAULT_MAX_COMPLETION_TOKENS = 16000


class _Function:
    def __init__(self, name, arguments):
        self.name = name
        self.arguments = arguments


class _ToolCall:
    def __init__(self, name, arguments):
        self.function = _Function(name, arguments)


class _AssistantMessage:
    """What this client appends as `resp.message`. `content`/`tool_calls`
    are the Ollama-shaped surface Session reads; `raw_tool_calls` is the
    exact `{"id", "type", "function": {"name", "arguments"}}` list the API
    returned (arguments still a JSON string) -- extra data Session never
    touches but this client's own `_translate_messages` reads back out on
    the next hop, so the assistant turn round-trips byte-for-byte."""

    def __init__(self, content, raw_tool_calls):
        self.content = content
        self.tool_calls = [
            _ToolCall(tc["function"]["name"], json.loads(tc["function"]["arguments"] or "{}"))
            for tc in raw_tool_calls
        ] or None
        self.raw_tool_calls = raw_tool_calls


class _Response:
    def __init__(self, message):
        self.message = message


def _translate_messages(messages):
    """Session's `self.messages` list -> a flat Chat Completions messages
    list. See module docstring for why this needs no `system_text`
    extraction and no same-turn tool-result batching, unlike the Anthropic
    client's `_translate_messages` -- and for why `last_tool_call_ids_by_name`
    is a per-name FIFO queue rather than a single id: a turn can call the
    same tool name more than once (parallel tool calls), and a plain dict
    would collapse them onto one id the way it did for Anthropic (see
    docs/memos/2026-09-07/2026-09-07-supervisor-robustness-memo.md,
    section 3)."""
    openai_messages = []
    last_tool_call_ids_by_name = defaultdict(list)

    for entry in messages:
        if isinstance(entry, _AssistantMessage):
            msg = {"role": "assistant", "content": entry.content or None}
            if entry.raw_tool_calls:
                msg["tool_calls"] = entry.raw_tool_calls
            openai_messages.append(msg)
            last_tool_call_ids_by_name = defaultdict(list)
            for tc in entry.raw_tool_calls:
                last_tool_call_ids_by_name[tc["function"]["name"]].append(tc["id"])
            continue

        role = entry.get("role")
        if role == "tool":
            ids = last_tool_call_ids_by_name[entry["tool_name"]]
            tool_call_id = ids.pop(0) if ids else None
            openai_messages.append({
                "role": "tool",
                "tool_call_id": tool_call_id,
                "content": entry["content"],
            })
        else:
            openai_messages.append({"role": role, "content": entry["content"]})

    return openai_messages


class OpenAIClient:
    def __init__(self, api_key, model=DEFAULT_MODEL, max_completion_tokens=DEFAULT_MAX_COMPLETION_TOKENS):
        self.model = model
        self.max_completion_tokens = max_completion_tokens
        self._client = openai.OpenAI(api_key=api_key)

    def chat(self, messages, tools=None):
        """Return a _Response whose `.message` matches OllamaClient's
        `.chat()` return shape -- see module docstring."""
        openai_messages = _translate_messages(messages)
        kwargs = {}
        if tools:
            kwargs["tools"] = tools

        response = self._client.chat.completions.create(
            model=self.model,
            max_completion_tokens=self.max_completion_tokens,
            messages=openai_messages,
            **kwargs,
        )

        message = response.choices[0].message
        if getattr(message, "refusal", None):
            return _Response(_AssistantMessage(message.refusal, []))

        raw_tool_calls = [
            {"id": tc.id, "type": tc.type, "function": {"name": tc.function.name, "arguments": tc.function.arguments}}
            for tc in (message.tool_calls or [])
        ]
        return _Response(_AssistantMessage(message.content or "", raw_tool_calls))
